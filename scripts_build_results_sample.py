"""Builds results.sample.json: a structurally-valid, clearly-labeled SAMPLE
results file for W-A3 dev/test use only.

Per SPEC-model-bench.md section 10's task split: "W-A3 (no secrets): page +
functions written against a results.sample.json fixture." No real model run
exists yet (report.py refuses to run against data/prices.json's placeholder
zero prices -- Gate 1 is still open, see CONTEXT.md). This script produces a
same-shaped stand-in so the page (web/index.template.html), its render logic
(web/model-bench-render.js), and the local dev server can be built and
visually checked before real numbers exist.

This is NOT real benchmark data. Every number below is generated by a fixed
formula from a fixed seed, not measured from any model. It must never be
presented to a site visitor as a real result:
  - The real intent/group NAMES and the row count (3,080, n_rows_expected)
    come from the actual Banking77 pull (data/_labels.json,
    data/coarse_map.json) so the page's structure is exercised honestly.
  - The accuracy/cost/latency/calibration NUMBERS are synthetic by
    deliberate, deterministic design (round-ish, evenly-spaced values) so
    they read as obviously fixture-shaped rather than plausible-real, and
    so re-running this script always reproduces the same file (no
    hidden randomness to accidentally commit a different "sample" later).
  - scripts_build_web_page.py (the real page-build step) defaults to
    reading results.json, NOT this file -- results.sample.json is only
    ever passed with an explicit --results flag, so a production build
    with no real results.json fails closed instead of silently shipping
    this sample data.

Regenerate with: python3 scripts_build_results_sample.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
DATA_DIR = REPO_ROOT / "data"
OUT_PATH = REPO_ROOT / "results.sample.json"

N_ROWS_EXPECTED = 3080

# key, display-ish ordering, deterministic per-model sample stats. Chosen so
# best accuracy, cheapest cost, and best-calibrated (lowest brier) are three
# DIFFERENT models -- the page's "Overall insights" bullets (accuracy-vs-cost
# gap, cheapest, best-calibrated) are only meaningfully testable if those
# don't all coincide on one model, the way a real 5-model comparison usually
# doesn't either.
MODEL_SAMPLE_STATS = [
    # key, accuracy_fine, accuracy_coarse, cost_per_1k_usd, p50_ms, p95_ms, brier
    ("claude-sonnet", 0.91, 0.95, 0.62, 640, 1100, 0.070),
    ("claude-haiku", 0.85, 0.91, 0.11, 310, 520, 0.095),
    ("nova", 0.83, 0.90, 0.07, 260, 480, 0.130),
    ("llama", 0.79, 0.88, 0.09, 410, 700, 0.150),
    ("mistral", 0.75, 0.86, 0.05, 350, 610, 0.175),
]

N_ERRORS_BY_MODEL = {"claude-sonnet": 0, "claude-haiku": 2, "nova": 5, "llama": 12, "mistral": 18}


def _load_intents_and_groups() -> tuple[list[str], dict[str, str]]:
    with open(DATA_DIR / "_labels.json") as f:
        intents = json.load(f)
    with open(DATA_DIR / "coarse_map.json") as f:
        coarse_map = json.load(f)
    return intents, coarse_map


def _reliability_bins(accuracy_fine: float, overconfidence: float) -> list[dict]:
    """10 evenly-populated bins, mean_confidence at each bin's midpoint,
    observed_accuracy walking from below to above accuracy_fine as
    confidence rises -- shaped like a real (if idealized) calibration
    curve, offset by `overconfidence` so different sample models show
    visibly different calibration on the chart (a real thing worth being
    able to see even in fixture data)."""
    bins = []
    per_bin_n = N_ROWS_EXPECTED // 10
    for i in range(10):
        mean_confidence = i * 10 + 5
        # Linear ramp from (accuracy_fine - 0.35) to (accuracy_fine + 0.15),
        # clamped to [0, 1], then shifted by the model's overconfidence bias.
        raw = (accuracy_fine - 0.35) + (i / 9) * 0.50 - overconfidence
        observed_accuracy = max(0.0, min(1.0, raw))
        bins.append(
            {
                "bin": f"{i * 10}-{i * 10 + 10}",
                "n": per_bin_n,
                "mean_confidence": float(mean_confidence),
                "observed_accuracy": round(observed_accuracy, 4),
            }
        )
    return bins


def _worst_first(names: list[str], base_accuracy: float, spread: float) -> list[dict]:
    """A full, sorted-worst-first list across `names`, each with a
    deterministic per-name accuracy so re-runs are stable. Uses each name's
    position in the (already-fixed) input list, not its hash, so the
    output is identical on every Python version/run."""
    n = len(names)
    rows = []
    for i, name in enumerate(names):
        # Spread values evenly around base_accuracy using position i, then
        # sort -- deterministic, no randomness module needed.
        offset = spread * (((i * 37) % n) / max(1, n - 1) - 0.5)
        acc = max(0.0, min(1.0, base_accuracy + offset))
        rows.append({"name": name, "n": max(1, N_ROWS_EXPECTED // n), "accuracy": round(acc, 4)})
    rows.sort(key=lambda r: r["accuracy"])
    return rows


def build_sample() -> dict:
    intents, coarse_map = _load_intents_and_groups()
    groups = sorted(set(coarse_map.values()))

    models_out = []
    for i, (key, acc_fine, acc_coarse, cost, p50, p95, brier) in enumerate(MODEL_SAMPLE_STATS):
        overconfidence = 0.05 + 0.03 * i  # each model a bit more overconfident than the last
        models_out.append(
            {
                "key": key,
                "model_id": f"<sample-only, not a real Bedrock id: {key}>",
                "adapter": "sample",
                "n_rows": N_ROWS_EXPECTED,
                "n_errors": N_ERRORS_BY_MODEL[key],
                "accuracy_fine": acc_fine,
                "accuracy_coarse": acc_coarse,
                "cost_per_1k_usd": cost,
                "latency_p50_ms": p50,
                "latency_p95_ms": p95,
                "brier": brier,
                "reliability": _reliability_bins(acc_fine, overconfidence),
                "worst_intents_fine": _worst_first(intents, acc_fine, spread=0.6),
                "worst_groups_coarse": _worst_first(groups, acc_coarse, spread=0.3),
            }
        )

    return {
        "generated_at": "2026-09-12T00:00:00+00:00",
        "prices_as_of": "SAMPLE-NOT-REAL",
        "n_rows_expected": N_ROWS_EXPECTED,
        "models": models_out,
        "sample_disclosure": (
            "This file is a disclosed, non-real SAMPLE for W-A3 dev/test use "
            "only (see this script's module docstring). It is never the "
            "default input to scripts_build_web_page.py and must never be "
            "deployed as the live page's data."
        ),
    }


def main() -> int:
    sample = build_sample()
    with open(OUT_PATH, "w") as f:
        json.dump(sample, f, indent=2)
        f.write("\n")
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
